/// free it.
pub struct LibString(NonNull<c_char>);

impl LibString {
    /// Borrows the string. The `&CStr` cannot outlive `self`.
    pub fn as_c_str(&self) -> &CStr {
        // SAFETY: the pointer came from `ffi_lab_greeting`, is non-NULL,
        // NUL-terminated and not freed before `self` is dropped; nothing
        // writes to it meanwhile.
        unsafe { CStr::from_ptr(self.0.as_ptr()) }
    }
}

impl Drop for LibString {
    fn drop(&mut self) {
        // SAFETY: the pointer came from `ffi_lab_greeting` and is released
        // exactly once, here, by the library that allocated it.
        unsafe { sys::ffi_lab_string_free(self.0.as_ptr()) };
    }
}

/// Asks the pretend C library for `"Hello, <name>!"` and takes ownership of
/// the result. `None` if the library returned NULL.
