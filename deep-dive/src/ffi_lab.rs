/// What `user` points to while C runs our callback: the closure, plus the
/// payload of a panic caught in it.
struct TrampolineState<F> {
    f: F,
    panic: Option<Box<dyn Any + Send>>,
}

/// The `cb` handed to C. One copy per closure type `F` (monomorphization),
/// so each copy knows what `user` really points to.
///
/// # Safety
///
/// `user` must point to a live `TrampolineState<F>` for this very `F`, not
/// accessed by anything else during the call.
unsafe extern "C" fn trampoline<F: FnMut(i32)>(user: *mut c_void, x: c_int) {
    // SAFETY: `for_each_catching` passes a pointer to its local
    // `TrampolineState<F>` and does not touch it until the C function
    // returns; the C function calls us synchronously, one call at a time, so
    // this `&mut` is unique while it exists.
    let state = unsafe { &mut *user.cast::<TrampolineState<F>>() };
    if state.panic.is_some() {
        // An earlier call panicked, and this C API cannot be told to stop:
        // skip the remaining elements.
        return;
    }
    // A panic must not unwind out of an `extern "C"` function (the process
    // would abort), so catch it here and carry it back to Rust. Asserting
    // unwind safety is fine: nothing here is used again after a panic, except
    // the payload slot.
    if let Err(payload) = panic::catch_unwind(AssertUnwindSafe(|| (state.f)(x))) {
        state.panic = Some(payload);
    }
}

/// Calls `f` on every element of `xs` through the C function
/// `ffi_lab_for_each`. Returns `Err(payload)` if `f` panicked; the elements
/// after the panicking one are skipped. `f` is dropped exactly once, either
/// way.
pub fn for_each_catching<F: FnMut(i32)>(xs: &[i32], f: F) -> Result<(), Box<dyn Any + Send>> {
    let mut state = TrampolineState { f, panic: None };
    // SAFETY: `xs.as_ptr()` is valid for `xs.len()` reads (an `i32` is a C
    // `int`). `trampoline::<F>` matches the `TrampolineState<F>` behind
    // `user`, which lives on this stack frame until after the call and is not
    // touched by us meanwhile. `ffi_lab_for_each` calls back synchronously and
    // keeps neither pointer after it returns.
    unsafe {
        sys::ffi_lab_for_each(
            xs.as_ptr(),
            xs.len(),
            Some(trampoline::<F>),
            (&raw mut state).cast(),
        );
    }
    match state.panic {
        Some(payload) => Err(payload),
        None => Ok(()),
    }
}

/// The safe API: calls `f` on every element of `xs` through C, and if `f`
/// panics, the panic continues on the Rust side (`resume_unwind`) once the C
/// function has returned, as if C were not there.
///
/// ```
/// use deep_dive::ffi_lab::for_each;
///
/// let mut sum = 0;
/// for_each(&[1, 2, 3], |x| sum += x);
/// assert_eq!(sum, 6);
/// ```
pub fn for_each<F: FnMut(i32)>(xs: &[i32], f: F) {
    if let Err(payload) = for_each_catching(xs, f) {
        panic::resume_unwind(payload);
    }
}

/// The `"C-unwind"` trampoline: no `catch_unwind`, because this ABI lets a
/// panic unwind out of it.
///
/// # Safety
///
/// `user` must point to a live `F`, not accessed by anything else during the
/// call.
unsafe extern "C-unwind" fn trampoline_unwind<F: FnMut(i32)>(user: *mut c_void, x: c_int) {
    // SAFETY: `for_each_unwind` passes a pointer to its local `F` and does not
    // touch it until the C function returns (or unwinds).
    let f = unsafe { &mut *user.cast::<F>() };
    f(x);
}

/// Like [`for_each`], but through `ffi_lab_for_each_unwind`, whose ABI is
/// `"C-unwind"`: a panic in `f` unwinds straight through the foreign frame.
/// Only valid for foreign code built to be unwound through; the stand-in
/// library is Rust, so it is.
pub fn for_each_unwind<F: FnMut(i32)>(xs: &[i32], mut f: F) {
    // SAFETY: as in `for_each_catching`: `xs` is valid for `xs.len()` reads,
    // `trampoline_unwind::<F>` matches the `F` behind `user`, which outlives
    // the call, and the callee keeps no pointer. Both sides are `"C-unwind"`,
    // so a panic may cross them; `f` is then dropped by this frame's unwind.
    unsafe {
        sys::ffi_lab_for_each_unwind(
            xs.as_ptr(),
            xs.len(),
            Some(trampoline_unwind::<F>),
            (&raw mut f).cast(),
        );
    }
}

