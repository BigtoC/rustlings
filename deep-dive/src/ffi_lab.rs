/// Owns one `ctx *` from the pretend C library and frees it in `Drop`.
///
/// `Send` (by the `unsafe impl` below) but not `Sync`: share it between
/// threads as `Mutex<Handle>`.
///
/// Without `unsafe impl Send`, a handle is not `Send`, because `NonNull` is
/// not (E0277):
///
/// ```compile_fail,E0277
/// use deep_dive::ffi_lab::Ctx;
/// use std::ptr::NonNull;
///
/// struct Handle(NonNull<Ctx>);
///
/// fn assert_send<T: Send>() {}
/// assert_send::<Handle>();
/// ```
///
/// With it, it is (positive control, one line longer):
///
/// ```
/// use deep_dive::ffi_lab::Ctx;
/// use std::ptr::NonNull;
///
/// struct Handle(NonNull<Ctx>);
/// // SAFETY: (see the real `Handle` for the argument)
/// unsafe impl Send for Handle {}
///
/// fn assert_send<T: Send>() {}
/// assert_send::<Handle>();
/// ```
///
/// The real `Handle` is not `Sync` (E0277):
///
/// ```compile_fail,E0277
/// use deep_dive::ffi_lab::Handle;
///
/// fn assert_sync<T: Sync>() {}
/// assert_sync::<Handle>();
/// ```
///
/// but a `Mutex<Handle>` is (positive control):
///
/// ```
/// use deep_dive::ffi_lab::Handle;
/// use std::sync::Mutex;
///
/// fn assert_sync<T: Sync>() {}
/// assert_sync::<Mutex<Handle>>();
/// ```
pub struct Handle(NonNull<Ctx>);

impl Handle {
    /// Creates a context through the C library.
    pub fn new() -> Handle {
        let raw = sys::ffi_lab_ctx_new();
        Handle(NonNull::new(raw).expect("ffi_lab_ctx_new never returns NULL"))
    }

    /// Increments the context's counter and returns the new value.
    pub fn bump(&self) -> i32 {
        // SAFETY: `self.0` is a live context (freed only in `Drop`). `Handle`
        // is not `Sync`, so every `&Handle` stays on one thread, and `bump`
        // does not call back into Rust: no other call on this context can run
        // at the same time.
        unsafe { sys::ffi_lab_ctx_bump(self.0.as_ptr()) }
    }
}

impl Default for Handle {
    fn default() -> Handle {
        Handle::new()
    }
}

impl Drop for Handle {
    fn drop(&mut self) {
        // SAFETY: `self.0` came from `ffi_lab_ctx_new`; `Drop` runs once and
        // nothing can use the handle afterwards, so it is freed exactly once.
        unsafe { sys::ffi_lab_ctx_free(self.0.as_ptr()) };
    }
}

// SAFETY: the library allows a context to be used from any thread, as long as
// calls on it do not overlap: it has no thread-local state and no thread
// affinity. Moving the only `Handle` to another thread moves the right to call
// into the context along with it, and `Drop` may free it on whichever thread
// holds it last. Deliberately NOT `Sync`: a shared `&Handle` on two threads
// could run `bump` on the same context concurrently, a data race in C.
unsafe impl Send for Handle {}

