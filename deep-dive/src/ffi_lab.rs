    static LIBRARY_TESTS: Mutex<()> = Mutex::new(());

    fn serialize_library_tests() -> MutexGuard<'static, ()> {
        LIBRARY_TESTS.lock().unwrap_or_else(PoisonError::into_inner)
    }

