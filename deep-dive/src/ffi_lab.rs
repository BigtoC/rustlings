    // ----- Part 3 · callback_trampoline -----

    #[test]
    fn for_each_passes_every_value_to_the_closure() {
        let drops = Cell::new(0);
        let mut seen = Vec::new();
        {
            let guard = DropCounter(&drops);
            let seen = &mut seen;
            for_each(&[3, 1, 4, 1, 5], move |x| {
                let _keep_alive = &guard;
                seen.push(x);
            });
        }
        assert_eq!(seen, [3, 1, 4, 1, 5]);
        // The closure (and the guard it owns) was dropped exactly once, by
        // `for_each_catching`, not per call and not never.
        assert_eq!(drops.get(), 1);
    }

    #[test]
    fn empty_slice_never_calls_the_closure() {
        let mut calls = 0;
        for_each(&[], |_| calls += 1);
        assert_eq!(calls, 0);
    }

    #[test]
    fn panicking_closure_returns_err() {
        let drops = Cell::new(0);
        let mut seen = Vec::new();
        let result = {
            let guard = DropCounter(&drops);
            let seen = &mut seen;
            for_each_catching(&[1, 2, 3, 4], move |x| {
                let _keep_alive = &guard;
                seen.push(x);
                if x == 2 {
                    panic!("closure panicked at {x}");
                }
            })
        };
        let payload = result.unwrap_err();
        assert_eq!(message(&*payload), "closure panicked at 2");
        // Calls after the panic were skipped, and the closure was still
        // dropped exactly once.
        assert_eq!(seen, [1, 2]);
        assert_eq!(drops.get(), 1);
    }

    #[test]
    fn for_each_resumes_the_panic_on_the_rust_side() {
        let result = panic::catch_unwind(|| for_each(&[1, 2], |_| panic!("boom")));
        assert_eq!(message(&*result.unwrap_err()), "boom");
    }

    #[test]
    fn c_unwind_lets_the_panic_through() {
        let drops = Cell::new(0);
        let mut seen = Vec::new();
        let result = panic::catch_unwind(AssertUnwindSafe(|| {
            let guard = DropCounter(&drops);
            let seen = &mut seen;
            for_each_unwind(&[1, 2, 3], move |x| {
                let _keep_alive = &guard;
                seen.push(x);
                if x == 2 {
                    panic!("unwound through C-unwind");
                }
            });
        }));
        assert_eq!(message(&*result.unwrap_err()), "unwound through C-unwind");
        // The unwind stopped the loop in the "C" function and dropped the
        // closure on its way out.
        assert_eq!(seen, [1, 2]);
        assert_eq!(drops.get(), 1);
    }

    const ABORT_CHILD_ENV: &str = "FFI_LAB_ABORT_CHILD";

    /// Runs in a child process only (see the next test): a panic reaches the
    /// end of an `extern "C"` function, and the process aborts. Without the
    /// environment variable it does nothing, so `cargo test -- --ignored`
    /// stays safe to run.
    #[test]
    #[ignore = "aborts the process on purpose; run by panic_through_extern_c_aborts_the_process"]
    fn child_panics_through_extern_c() {
        if std::env::var_os(ABORT_CHILD_ENV).is_none() {
            eprintln!("skipped: set {ABORT_CHILD_ENV}=1 to let this test abort the process");
            return;
        }
        broken::for_each_unguarded(&[1, 2, 3], |x| {
            if x == 2 {
                panic!("callback panicked at {x}");
            }
        });
        unreachable!("the process aborts before for_each_unguarded returns");
    }

    #[test]
    #[cfg_attr(miri, ignore = "Miri cannot spawn processes")]
    fn panic_through_extern_c_aborts_the_process() {
        // Re-run this test binary, filtered to the one ignored test above.
        // Test names omit the crate name: `ffi_lab::tests::...`.
        let (_crate_name, module) = module_path!().split_once("::").unwrap();
        let test_name = format!("{module}::child_panics_through_extern_c");
        let exe = std::env::current_exe().unwrap();
        let output = std::process::Command::new(exe)
            .args(["--ignored", "--exact", &test_name, "--nocapture"])
            .env(ABORT_CHILD_ENV, "1")
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);

        assert!(
            stdout.contains("running 1 test"),
            "the filter matched no test:\n{stdout}"
        );
        assert!(
            !output.status.success(),
            "the child exited normally:\n{stderr}"
        );
        #[cfg(unix)]
        {
            use std::os::unix::process::ExitStatusExt;
            const SIGABRT: i32 = 6; // the same number on Linux and macOS
            assert_eq!(output.status.signal(), Some(SIGABRT), "{stderr}");
        }
        // First the closure's panic, then the abort at the ABI boundary.
        assert!(stderr.contains("callback panicked at 2"), "{stderr}");
        assert!(
            stderr.contains("panic in a function that cannot unwind"),
            "{stderr}"
        );
    }

