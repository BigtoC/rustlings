//! Lab · FFI: `unsafe extern` and `safe fn`, `repr(C)`, `CString`, trampolines
//!
//! Rust calls C, and C calls Rust, through the C ABI: integers, floats, raw
//! pointers, `repr(C)` structs and `extern "C"` function pointers. Nothing is
//! checked across that line. A declaration in an `extern` block is an
//! unchecked import (the linker matches the name, never the signature), which
//! is why edition 2024 makes you write `unsafe extern`. The lab has four parts,
//! one per question an FFI interview asks:
//!
//! 1. **Calling C** (`call_libc`): declare `strlen`, `abs`, `div`, `qsort` and
//!    `hypot`, get a `repr(C)` struct back by value, pass a Rust comparator to
//!    `qsort`. Which of them may be declared `safe fn`?
//! 2. **Strings and ownership** (`cstring_ownership`): `CString` vs `CStr`,
//!    `into_raw` / `from_raw`, a `#[unsafe(no_mangle)]` export, and the
//!    `as_ptr()` on a temporary that dangles. Who frees what?
//! 3. **Closures through a C callback** (`callback_trampoline`): a generic
//!    `extern "C"` trampoline behind a safe
//!    `for_each(&[i32], impl FnMut(i32))`, and what a panic in the closure
//!    does.
//! 4. **A C handle across threads** (`send_c_handle`): a non-thread-safe C
//!    context wrapped so that it is `Send` but not `Sync`, and shared through a
//!    `Mutex`.
//!
//! Compare with the graded exercises:
//!
//! - `30_send_sync/send_sync3`: the `assert_send` / `assert_sync` compile-time
//!   checks that part 4 uses.
//! - `56_async_bounds/async_send1`: std's `MutexGuard` is `Sync` but not
//!   `Send` (a pthread mutex must be unlocked by the thread that locked it).
//!   Part 4's `Handle` is the mirror image: `Send` but not `Sync`, like
//!   `Cell` and `RefCell`.
//! - `49_panics`: `panic1` catches a panic at a boundary, and the README's
//!   "Unwind or Abort" table lists the `extern "C"` abort that part 3 checks
//!   in a child process.
//! - `41_memory_layout/layout2`: what `repr(C)` does and does not guarantee.
//! - `33_closures`: every closure has its own type, which is what lets one
//!   generic trampoline serve them all. The `raw_waker` lab uses the same
//!   trick: a type-erased data pointer plus functions that know its real type.
//!
//! # The C side of this lab
//!
//! Part 1 calls the real C library (glibc's `libc` and `libm` on Linux,
//! `libSystem` on macOS). std links both already, so there is no build script.
//! Part 3 needs a C API that takes a callback plus a `void *user` pointer,
//! and libc has no portable one: `qsort_r` exists on glibc and on macOS with
//! different argument orders (glibc takes the comparator and then `arg`, and
//! calls `compar(a, b, arg)`; macOS takes `arg` first and calls
//! `compar(arg, a, b)`). Parts 2 and 4 need a library that hands out strings
//! and contexts it allocated itself. So the lab brings a tiny "C library" of
//! its own, written in Rust (the private module `fake_c`): `extern "C"`
//! functions exported under `ffi_lab_*` symbol names with
//! `#[unsafe(no_mangle)]`. The Rust side imports them back *by name* through
//! an `unsafe extern "C"` block (the private module `sys`), exactly as
//! bindings to a real C library (hand-written, or generated by bindgen) would.
//! In a real project the C code would be compiled by a build script (the `cc`
//! crate) or linked from a system library; keeping it in Rust means no C
//! compiler, and Miri can execute both sides.
//!
//! # 1. Calling C: what exactly is unsafe?
//!
//! - The `unsafe` in `unsafe extern "C" { .. }` is on the *declaration*: you
//!   promise that each symbol exists with exactly this signature and ABI.
//!   Nothing checks it, and a wrong signature is undefined behavior at the
//!   first call. Since edition 2024 a plain `extern` block is an error
//!   ("extern blocks must be unsafe").
//! - Every function in the block is unsafe to call unless it is marked
//!   `safe fn`. `safe fn` is a second promise: no argument values of the
//!   declared types can cause undefined behavior, and there is no other
//!   precondition (no pointer to validate, no global state to set up first,
//!   no thread restriction).
//! - [`hypot`] keeps that promise: every pair of `f64`s, NaNs and infinities
//!   included, has a defined result, and it takes no pointers. (On overflow
//!   ISO C lets it report a range error in the calling thread's `errno`, which
//!   is harmless.) std declares it (along with `tan`, `atan2`, `cosh` and
//!   friends) the same way, as `pub safe fn hypot(x: f64, y: f64) -> f64;` in
//!   `library/std/src/sys/cmath.rs`.
//! - `abs` and `div` look just as harmless, and are not. ISO C makes
//!   `abs(INT_MIN)` undefined (the result does not fit in an `int`), and
//!   `div(x, 0)` and `div(INT_MIN, -1)` too. Declared `safe fn`, they would
//!   let safe code call `abs(i32::MIN)`: an unsound binding, even though it
//!   compiles. So they stay `unsafe fn`, and the safe API is a checked wrapper
//!   that rejects the bad inputs before the call: [`checked_abs`] and
//!   [`checked_div`]. An unsafe raw binding plus a safe wrapper that
//!   establishes its preconditions is the shape of every `-sys` crate and the
//!   safe crate on top of it. (Real code would call `i32::checked_abs`; the
//!   pattern is the point.) Undefined behavior does not have to crash: on the
//!   aarch64 Mac this lab was written on, `abs(INT_MIN)` returns `INT_MIN` and
//!   `div(1, 0)` returns `{ quot: 0, rem: 1 }`, silently.
//! - `div` returns a `div_t` *by value*, so Rust needs a struct with the same
//!   layout: [`DivT`] is `#[repr(C)]`, which keeps the declared field order and
//!   C's padding. ISO C allows `quot` and `rem` "in either order", so the
//!   order is copied from the platform's header (macOS's and glibc's both put
//!   `quot` first; bindgen does this copying for you). Remove the `repr(C)`
//!   and rustc warns that the type "is not FFI-safe" (`improper_ctypes`).
//! - `qsort` takes a comparator `int (*)(const void *, const void *)`, and a
//!   Rust `unsafe extern "C" fn` fits it. A C function pointer that may be
//!   NULL is spelled `Option<fn>` (same size and ABI, `None` is NULL). The
//!   comparator uses `Ord::cmp`, never the C idiom `*a - *b`, which overflows
//!   for `i32::MIN - 1`. There is no `void *user` argument, so a comparator
//!   cannot capture anything, and closures are out (part 3 is for APIs that
//!   take one). A safe *generic* `qsort<T: Ord>` wrapper would even be
//!   unsound: ISO C makes an inconsistent comparator undefined behavior, while
//!   a safe `Ord` impl is allowed to be inconsistent (Rust's own `sort` stays
//!   memory safe even then). `i32`'s `Ord` is a total order, so [`qsort_i32`]
//!   is fine.
//! - `strlen` reads until it finds a NUL, so its argument must be
//!   NUL-terminated. `&CStr` guarantees exactly that, which makes [`c_strlen`]
//!   safe.
//!
//! # 2. Strings: who owns the bytes, and who frees them?
//!
//! - `CString::new(s)` takes the bytes of `s` (copying them if `s` is
//!   borrowed, like a `&str`) and appends a NUL. It fails with a `NulError`
//!   if `s` contains a NUL byte, because C would see the string end there:
//!   `nul_position()` says where, and `into_vec()` returns your bytes.
//! - `&CStr` is the borrowed view, C's `const char *`: `c"..."` literals, or
//!   `CStr::from_ptr` on a pointer C gave you. C strings are bytes, not UTF-8:
//!   `to_str()` fails on invalid UTF-8, while `to_string_lossy()` substitutes
//!   U+FFFD (and allocates only then).
//! - `as_ptr()` borrows: the pointer is valid while the `CString` lives. In
//!   `let p = CString::new(s).unwrap().as_ptr();` the temporary `CString` is
//!   dropped at the `;`, so `p` dangles. rustc warns
//!   (`dangling_pointers_from_temporaries`, warn by default) and Miri reports
//!   "memory access failed: allocN has been freed, so this pointer is
//!   dangling". [`c_len`] binds the `CString` to a local instead.
//! - `into_raw()` hands ownership to C, and the only correct way to free that
//!   pointer is `CString::from_raw` on the Rust side: C must give it back, and
//!   must not change the string's length meanwhile. C's `free` on it mixes
//!   allocators, which Miri reports as "deallocating allocN, which is Rust heap
//!   memory, using C heap deallocation operation". It can seem to work
//!   natively while Rust's global allocator happens to be `malloc`, and breaks
//!   once a program installs a different `#[global_allocator]`.
//! - The same rule runs the other way: memory the C library allocated goes
//!   back to the C library. `ffi_lab_greeting` returns a string that the
//!   caller must release with `ffi_lab_string_free`, and [`LibString`] is the
//!   owning Rust wrapper whose `Drop` does that, exactly once.
//! - `#[unsafe(no_mangle)]` exports a function under its plain name, so C can
//!   link to it. It is an unsafe *attribute* since edition 2024 (a bare
//!   `#[no_mangle]` is "unsafe attribute used without unsafe") because the
//!   name can collide with another symbol in the program, for example the C
//!   library's own `free`, and nothing checks that. Hence the `ffi_lab_`
//!   prefix on every symbol this lab exports.
//! - An exported function that dereferences a raw pointer argument is a
//!   `pub unsafe extern "C" fn` with a `# Safety` section. C callers do not
//!   see the `unsafe`; Rust callers do. For a function in the crate's public
//!   API, clippy's deny-by-default `not_unsafe_ptr_arg_deref` insists; it
//!   skips `fake_c`, a private module, so there the rule is kept by hand.
//!
//! # 3. A closure through `void (*cb)(void *user, int x)`
//!
//! A C function pointer is a bare code address: it cannot carry a closure's
//! captured state. C APIs solve this with the `void *user` pointer that they
//! pass back to every callback. So:
//!
//! 1. Put the closure (plus a slot for a panic payload) in a
//!    `TrampolineState<F>` on the Rust stack and pass a pointer to it as
//!    `user`.
//! 2. Pass `trampoline::<F>` as `cb`: a generic `unsafe extern "C" fn`,
//!    monomorphized once per closure type, so each copy knows what `user`
//!    really points to. It casts `user` back to `&mut TrampolineState<F>` and
//!    calls the closure.
//! 3. Wrap both in a safe function, [`for_each`], whose signature ties the
//!    pointer's lifetime to the call. That is sound only because this C
//!    function calls `cb` synchronously and keeps neither pointer after it
//!    returns. An API that stores the callback for later needs a heap
//!    allocation (`Box<F>`), a `'static` (and often `Send`) bound, and a
//!    matching "destroy" callback that frees it.
//!
//! A panic must not leave an `extern "C"` function: since Rust 1.81 it aborts
//! the whole process with "panic in a function that cannot unwind" (before
//! that it was undefined behavior). So `trampoline` wraps the call in
//! `catch_unwind`, stores the payload, skips the remaining callbacks, and
//! [`for_each_catching`] returns `Err(payload)` once C has returned;
//! [`for_each`] resumes the panic on the Rust side with `resume_unwind`. The
//! alternative is the `"C-unwind"` ABI (Rust 1.71): when both the callback and
//! the C function are declared `extern "C-unwind"`, a panic may unwind
//! through the foreign frames ([`for_each_unwind`]). That is only defined if
//! the foreign code was built to be unwound through (C++, or C compiled with
//! `-fexceptions`), which is why catching at the boundary is the usual
//! answer. The broken trampoline, without `catch_unwind`, is kept in the
//! tests' `broken` module; a test runs it in a child process and checks that
//! the process died of `SIGABRT` with that message.
//!
//! # 4. A non-thread-safe C handle: `Send`, not `Sync`
//!
//! The pretend C library hands out a `ctx *` whose functions do no locking.
//! Its (pretend) documentation says: "a context may be used from any thread,
//! but calls on one context must not overlap". [`Ctx`] is declared the way
//! the Rustonomicon recommends for an opaque C type, and [`Handle`] owns one
//! `ctx *`, freeing it in `Drop`.
//!
//! - `Handle(NonNull<Ctx>)` starts out neither `Send` nor `Sync`, because raw
//!   pointers, `NonNull` included, are neither. Auto traits cannot know what a
//!   pointer points to, so the author must decide.
//! - `unsafe impl Send for Handle` is justified by the contract: the context
//!   has no thread affinity, and moving the only `Handle` moves the right to
//!   call into it. A library whose objects must stay on their creating thread
//!   (GUI toolkits whose objects belong to the main thread, or a library that
//!   keeps its state in thread-local storage) would get no `Send` either.
//! - `Sync` would be unsound. `Handle: Sync` makes `&Handle: Send`, so safe
//!   code could share one handle between threads (`Arc<Handle>`, scoped
//!   threads) and call [`Handle::bump`] on the same context from two threads
//!   at once: a data race inside C, which is undefined behavior. The tests'
//!   `broken::SyncHandle` does exactly that, and Miri reports "Data race
//!   detected". (If every method took `&mut self`, a shared `&Handle` could do
//!   nothing and `Sync` would be harmless; that is the idea behind the
//!   unstable `std::sync::SyncView`, formerly `Exclusive`.)
//! - To share it, wrap it: `Mutex<T>` is `Sync` whenever `T: Send`, and the
//!   lock serializes the calls. So `Arc<Mutex<Handle>>` is the thread-safe
//!   handle, and the `unsafe impl Send` is what makes it possible.
//!
//! # Invariants
//!
//! - Every pointer given to C is valid for exactly what the function reads or
//!   writes, for the whole call: `&[i32]` becomes a (pointer, length) pair,
//!   `&CStr` a NUL-terminated string. An empty slice's pointer is dangling
//!   (non-NULL, aligned, pointing at nothing), so it goes only to functions
//!   documented to read nothing when the length is 0 (`ffi_lab_for_each`).
//!   The C standard library makes no such promise (its functions want valid
//!   pointers even for zero elements), so `qsort_i32` never calls `qsort` for
//!   fewer than two elements.
//! - Memory goes back to the allocator it came from: `CString::into_raw` to
//!   `CString::from_raw`, library strings to `ffi_lab_string_free`, a context
//!   to `ffi_lab_ctx_free`, each exactly once.
//! - No panic crosses an `extern "C"` boundary: trampolines catch, and the
//!   exported functions never panic (a failure becomes NULL).
//! - A trampoline's `user` points to a live `TrampolineState<F>` for exactly
//!   the `F` it was instantiated with.
//! - Calls on one context never overlap: `Handle` is `!Sync`.
//! - `safe fn` only for foreign functions with no preconditions at all.
//!
//! # Sharpest question
//!
//! *How do you pass a Rust closure to a C API that takes
//! `void (*cb)(void*, int)` plus a `void* user` pointer, and what happens if
//! the closure panics?* Pass a pointer to the closure (in a state struct) as
//! `user`, and a generic `extern "C" fn trampoline<F: FnMut(i32)>` as `cb`;
//! the trampoline casts `user` back to `&mut F` and calls it. Hide both behind
//! a safe function that borrows the closure for the duration of the call,
//! which is sound only if C does not keep the pointers after returning (if it
//! does, box the closure and free it from a destroy callback). A panic that
//! reaches the end of an `extern "C"` function aborts the process (Rust 1.81
//! and later; undefined behavior before). So catch it with `catch_unwind`
//! inside the trampoline, stop or skip the remaining callbacks, and resume the
//! panic (or return an error) on the Rust side after the C function returns.
//! Only when the foreign code supports unwinding may both sides be declared
//! `extern "C-unwind"` and the panic unwind through.
//!
//! # What runs under Miri
//!
//! Miri can call `strlen`, `hypot` and the `ffi_lab_*` functions (it
//! resolves an `extern` declaration to a `#[no_mangle]` Rust function), so
//! parts 2 to 4 run under Miri, with its leak and double-free checks, all but
//! the child-process test. It has no shim for `abs`, `div` or `qsort`
//! ("unsupported operation: can't call foreign function `abs` on OS `linux`",
//! or `macos`), and it cannot spawn processes, so those tests are
