    #[test]
    fn handle_moves_to_another_thread() {
        let _serial = serialize_library_tests();
        let before = live_allocations();
        let handle = Handle::new();
        assert_eq!(handle.bump(), 1);
        let handle = thread::Builder::new()
            .spawn(move || {
                assert_eq!(handle.bump(), 2);
                handle
            })
            .unwrap()
            .join()
            .unwrap();
        assert_eq!(handle.bump(), 3);
        assert_eq!(live_allocations(), before + 1);
        drop(handle);
        assert_eq!(live_allocations(), before);
    }

    #[test]
    fn mutex_shares_one_context_between_threads() {
        const THREADS: usize = 4;
        const BUMPS: usize = if cfg!(miri) { 5 } else { 1_000 };
        let _serial = serialize_library_tests();
        let before = live_allocations();
        let shared = Mutex::new(Handle::new());
        thread::scope(|s| {
            for _ in 0..THREADS {
                thread::Builder::new()
                    .spawn_scoped(s, || {
                        for _ in 0..BUMPS {
                            shared.lock().unwrap().bump();
                        }
                    })
                    .unwrap();
            }
        });
        let handle = shared.into_inner().unwrap();
        // Every bump happened, none was lost to a race.
        assert_eq!(handle.bump(), (THREADS * BUMPS) as i32 + 1);
        drop(handle);
        assert_eq!(live_allocations(), before);
    }

    /// Demonstration: why `Handle` must not be `Sync`. Two threads share a
    /// `&SyncHandle` and bump the same context. Miri reports "Data race
    /// detected between (1) non-atomic write on thread `unnamed-..` and (2)
    /// non-atomic read on thread `unnamed-..`":
    ///
    /// ```text
    /// cargo +nightly miri test --manifest-path deep-dive/Cargo.toml --lib -- --ignored --exact ffi_lab::tests::sync_handle_lets_two_threads_race
    /// ```
    ///
    /// The barrier makes the report independent of the schedule: once both
    /// threads are past it, nothing orders the two bumps, in any execution.
    /// Without it, 3 of 20 Miri seeds reported nothing when this was written:
    /// in those executions some other synchronization happened to order the
    /// two calls. The race was still in the code; Miri only reports the races
    /// of the execution it explores.
    #[test]
    #[ignore = "undefined behavior on purpose: run under Miri (see the doc comment)"]
    fn sync_handle_lets_two_threads_race() {
        if !cfg!(miri) {
            eprintln!("skipped natively: this is a data race; run it under Miri");
            return;
        }
        let _serial = serialize_library_tests();
        let shared = broken::SyncHandle(Handle::new());
        let both_started = Barrier::new(2);
        thread::scope(|s| {
            for _ in 0..2 {
                thread::Builder::new()
                    .spawn_scoped(s, || {
                        both_started.wait();
                        shared.bump()
                    })
                    .unwrap();
            }
        });
    }
